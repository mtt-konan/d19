def canonical_projection_bytes(projection: Any) -> bytes:
    return json.dumps(
        projection,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")


def projection_sha256(projection: Any) -> str:
    return hashlib.sha256(canonical_projection_bytes(projection)).hexdigest()


